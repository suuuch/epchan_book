"""Regenerate ``epchan/_rztcrit_tables.py`` from the original MATLAB file.

The MATLAB ``rztcrit.m`` embeds five large tables of critical values (one per
sample size bracket).  Rather than transcribing 1050 numbers by hand this
script parses the MATLAB source and writes the tables out as numpy arrays.

Usage::

    python python/tools/generate_rztcrit.py

MATLAB 的 ``rztcrit.m`` 内嵌了五张很大的临界值表（每张表对应一个样本量区间）。
与其手工誊写 1050 个数字，不如用本脚本解析 MATLAB 源码，并把表格输出成 numpy
数组。

用法::

    python python/tools/generate_rztcrit.py
"""

import re
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
MATLAB_FILE = REPO_ROOT / "matlab" / "rztcrit.m"
OUTPUT_FILE = Path(__file__).resolve().parents[1] / "epchan" / "_rztcrit_tables.py"

# The order of the tables inside rztcrit.m, with the sample size bracket each
# one applies to.
# rztcrit.m 中各张表的先后顺序，以及每张表所适用的样本量区间。
BRACKETS = [
    ("nobs >= 500", (500, None)),
    ("400 <= nobs <= 499", (400, 499)),
    ("300 <= nobs <= 399", (300, 399)),
    ("200 <= nobs <= 299", (200, 299)),
    ("1 <= nobs <= 199", (1, 199)),
]


def parse_tables(source):
    """Return the five ``(35 x 6)`` tables found in ``rztcrit.m``.
    返回 ``rztcrit.m`` 中的五张 ``(35 x 6)`` 表格。
    """
    blocks = re.findall(r"zt\s*=\s*\[(.*?)\]", source, re.S)
    if len(blocks) != 5:
        raise SystemExit("expected 5 tables in rztcrit.m, found %d" % len(blocks))
    tables = []
    for block in blocks:
        numbers = [float(n) for n in
                   re.findall(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?", block)]
        if len(numbers) != 35 * 6:
            raise SystemExit("expected 210 numbers per table, found %d" % len(numbers))
        tables.append(np.array(numbers, dtype=float).reshape(35, 6))
    return tables


def main():
    """Write the parsed tables out as a Python module.
    把解析出来的表格写成一个 Python 模块。
    """
    source = MATLAB_FILE.read_text(encoding="latin-1")
    tables = parse_tables(source)

    # The generated module is a plain list of numpy arrays.
    # 生成出来的模块就是一个由 numpy 数组组成的列表。
    lines = [
        '"""Critical value tables of the augmented Dickey-Fuller test.',
        "",
        "Generated by ``python/tools/generate_rztcrit.py`` from the original",
        "``rztcrit.m``; do not edit by hand.",
        '"""',
        "",
        "import numpy as np",
        "",
        "#: ``(name, (low, high), table)`` for every sample size bracket.",
        "TABLES = [",
    ]
    for (name, (low, high)), table in zip(BRACKETS, tables):
        lines.append("    (")
        lines.append("        %r," % name)
        lines.append("        (%d, %s)," % (low, "None" if high is None else str(high)))
        lines.append("        np.array([")
        for row in table:
            lines.append("            [%s]," % ", ".join("%.6g" % v for v in row))
        lines.append("        ]),")
        lines.append("    ),")
    lines.append("]")
    lines.append("")

    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s" % OUTPUT_FILE)


if __name__ == "__main__":
    sys.exit(main())
